import { hasKnownSocialIcon, type SocialBadgeItem } from "../lib/socials";

export function SocialBadges({ items }: { items: SocialBadgeItem[] }) {
  return (
    <div className="social-badges" aria-label="Confirmed social accounts">
      {items.map((item) => (
        <SocialBadge key={item.key} item={item} />
      ))}
    </div>
  );
}

function SocialBadge({ item }: { item: SocialBadgeItem }) {
  const inner = (
    <>
      <SocialMark slug={item.slug} label={item.site} />
      <span className="social-badge-check" aria-hidden>
        <CheckMark />
      </span>
    </>
  );
  const label = item.url ? `${item.site} profile` : `${item.site} account found`;
  if (item.url) {
    return (
      <a className="social-badge" href={item.url} target="_blank" rel="noreferrer noopener" title={item.site} aria-label={label}>
        {inner}
      </a>
    );
  }
  return (
    <span className="social-badge" title={item.site} aria-label={label}>
      {inner}
    </span>
  );
}

